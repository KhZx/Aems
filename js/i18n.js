let currentLang = localStorage.getItem('aems_lang') || 'en';

const _langSubscribers = new Set();

function applyLanguage() {
  const cfg = LANGS[currentLang];
  const html = document.documentElement;
  html.lang = currentLang;
  html.dir  = cfg.dir;
  document.documentElement.style.setProperty('--font-display', cfg.fontDisplay);
  document.documentElement.style.setProperty('--font-body', cfg.fontBody);

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key  = el.getAttribute('data-i18n');
    const attr = el.getAttribute('data-i18n-attr');
    const val  = t(key);
    if (attr) el.setAttribute(attr, val);
    else el.textContent = val;
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });

  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = t(el.getAttribute('data-i18n-html'));
  });

  document.querySelectorAll('.lang-toggle').forEach(btn => {
    btn.textContent = cfg.label;
  });

  // Notify dynamic views so they re-render with the new language.
  _langSubscribers.forEach(fn => { try { fn(currentLang); } catch { /* keep going */ } });
}

export function t(key, vars = {}) {
  let str = T[currentLang]?.[key] ?? T['en']?.[key] ?? key;
  Object.keys(vars).forEach(k => { str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), vars[k]); });
  return str;
}

export function getCurrentLang() { return currentLang; }

export function setLanguage(lang) {
  if (!T[lang] || lang === currentLang) return;
  currentLang = lang;
  localStorage.setItem('aems_lang', lang);
  applyLanguage();
}

// Subscribers are called after the static DOM has been re-translated so they
// can re-render anything built from JS state (cards, modals, charts, ...).
export function onLanguageChanged(fn) {
  if (typeof fn === 'function') _langSubscribers.add(fn);
  return () => _langSubscribers.delete(fn);
}

export function initI18n() { applyLanguage(); }
